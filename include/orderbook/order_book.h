#pragma once

#include "orderbook/types.h"
#include "orderbook/price_level.h"

#include <functional>
#include <map>
#include <unordered_map>
#include <vector>
#include <string>

namespace orderbook {

// ---------------------------------------------------------------------------
// Result of an add or cancel operation, so the caller can distinguish
// success from various error conditions without exceptions.
// ---------------------------------------------------------------------------
enum class Status : std::uint8_t {
    OK,
    REJECTED_ZERO_QUANTITY,
    REJECTED_DUPLICATE_ID,
    REJECTED_UNKNOWN_ID,
    REJECTED_MARKET_NO_LIQUIDITY
};

inline std::string to_string(Status s) {
    switch (s) {
        case Status::OK:                        return "OK";
        case Status::REJECTED_ZERO_QUANTITY:     return "REJECTED: zero quantity";
        case Status::REJECTED_DUPLICATE_ID:      return "REJECTED: duplicate order id";
        case Status::REJECTED_UNKNOWN_ID:        return "REJECTED: unknown order id";
        case Status::REJECTED_MARKET_NO_LIQUIDITY: return "REJECTED: no liquidity for market order";
    }
    return "UNKNOWN";
}

// ---------------------------------------------------------------------------
// AddResult: the status plus any trades generated by the add.
// ---------------------------------------------------------------------------
struct AddResult {
    Status             status;
    std::vector<Trade> trades;
};

// ---------------------------------------------------------------------------
// OrderBook: the matching engine for a single instrument.
//
// Data-structure overview
// -----------------------
//   bids_:  std::map<Price, PriceLevel, std::greater<>>
//   asks_:  std::map<Price, PriceLevel>
//
//   Both are ordered maps.  std::greater on the bids side means begin()
//   points to the *highest* bid — the best bid.  The default std::less on
//   the asks side means begin() points to the *lowest* ask — the best ask.
//   This makes "get best price" and "walk price levels in matching order"
//   simple forward iteration from begin().
//
//   order_locations_:  std::unordered_map<OrderId, LocationInfo>
//
//   Maps every live order id to:
//     - which side it is on (BUY / SELL)
//     - the map iterator to its price level
//     - the list iterator inside that price level
//
//   This gives O(1) average-case lookup and O(1) removal for cancel.
//   The list iterators remain valid because std::list guarantees iterator
//   stability across inserts and erases of *other* elements.
//
// Complexity summary (n = total orders, m = price levels)
// -------------------------------------------------------
//   add (no match):  O(log m)   – map::emplace to find/create the level
//   match per fill:  O(1)       – front of the best level
//   cancel:          O(1) avg   – unordered_map lookup + list erase
//                                 (+ O(log m) if the level becomes empty
//                                  and must be erased from the map)
// ---------------------------------------------------------------------------
class OrderBook {
public:
    // --- Core operations ----------------------------------------------------

    AddResult add_order(Order order);
    Status    cancel_order(OrderId id);

    // --- Queries (for PRINT / testing) --------------------------------------

    bool empty() const { return order_locations_.empty(); }
    std::size_t order_count() const { return order_locations_.size(); }

    bool has_order(OrderId id) const {
        return order_locations_.count(id) > 0;
    }

    // Snapshot helpers: return (price, total_qty) for the top `depth` levels.
    struct LevelInfo {
        Price    price;
        Quantity total_qty;
        std::size_t order_count;
    };
    std::vector<LevelInfo> top_bids(std::size_t depth = 5) const;
    std::vector<LevelInfo> top_asks(std::size_t depth = 5) const;

private:
    // --- Book sides ---------------------------------------------------------
    // Bids: highest price first (std::greater).
    // Asks: lowest price first  (default std::less).
    using BidMap = std::map<Price, PriceLevel, std::greater<>>;
    using AskMap = std::map<Price, PriceLevel>;

    BidMap bids_;
    AskMap asks_;

    // --- Fast order lookup for cancel ---------------------------------------
    //
    // For each live order we store enough information to jump straight to it
    // in O(1) average time:
    //   side        – tells us which map (bids_ or asks_) the order is in
    //   level_it    – iterator into that map (points to the PriceLevel)
    //   order_it    – iterator into the PriceLevel's std::list<Order>
    //
    // On cancel we:
    //   1. Look up OrderId in this map       → O(1) average
    //   2. Erase from the list via order_it  → O(1)
    //   3. If the PriceLevel is now empty,
    //      erase it from the map via level_it → O(1) amortized
    //   4. Erase from this map               → O(1) average
    //
    // We use a std::variant for the level iterator because it can point
    // into either BidMap or AskMap, which are different types.
    // ---------------------------------------------------------------------------
    struct BidLocation {
        BidMap::iterator          level_it;
        PriceLevel::Iterator      order_it;
    };
    struct AskLocation {
        AskMap::iterator          level_it;
        PriceLevel::Iterator      order_it;
    };
    struct LocationInfo {
        Side side;
        // We store the concrete location in a union-like pair of optionals.
        // Only one is populated, determined by `side`.
        BidLocation bid_loc;
        AskLocation ask_loc;
    };

    std::unordered_map<OrderId, LocationInfo> order_locations_;

    // --- Internal helpers ---------------------------------------------------
    std::vector<Trade> match_order(Order& incoming);
    void rest_order(Order order);

    // Remove a fully-filled resting order from the front of a price level,
    // then clean up the level if it's now empty.
    // Templated because BidMap and AskMap are distinct types.
    template <typename Map>
    void remove_filled_front(typename Map::iterator level_it, Map& book_side) {
        OrderId filled_id = level_it->second.front().id;
        level_it->second.pop_front();
        order_locations_.erase(filled_id);
        if (level_it->second.empty()) {
            book_side.erase(level_it);
        }
    }
};

} // namespace orderbook
